#!/usr/bin/env node
// Generates firestore.staging.rules from the real, production firestore.rules
// by changing EXACTLY two things: the semester id and the program start
// date. Every other line — ownership, idempotency, immutability, instructor
// allowlist, feed anonymity — is byte-for-byte identical, and this script
// verifies that at the end before writing anything.
//
// storage.rules needs no staging variant at all: it contains no date or
// semester logic (that only lives in firestore.rules), so the exact same
// storage.rules file is deployed to both the production and staging
// Firebase projects unchanged.
//
// Run: node scripts/generate-staging-rules.mjs
// Re-run this whenever STAGING_PROGRAM_START below drifts too far from
// "today" (it should stay within TOTAL_WEEKS of "now" for testing to make
// sense) — and update .env.staging / .env.staging.example to match.

import { readFileSync, writeFileSync } from 'node:fs';

// Keep these two in sync with .env.staging / .env.staging.example.
// Started 2 weeks before "this week" on purpose (not just "this week") so
// staging always has a genuinely expired week (week 1-2) to test "지난 주차
// 차단" against, a genuinely current week (week 3, this week) to test real
// submissions against immediately, and week 4+ to test "미래 주차 차단".
const STAGING_SEMESTER_ID = 'staging-2026';
const STAGING_PROGRAM_START_KST = '2026-08-17T00:00:00+09:00'; // Monday, 2 weeks before this week

const SRC = 'firestore.rules';
const OUT = 'firestore.staging.rules';

const original = readFileSync(SRC, 'utf8');

// Derive the timestamp.date(Y, M, D) + duration.value(H, 'h') expression the
// rules language needs, the same way the production rule encodes
// 2026-09-07T00:00:00+09:00 as timestamp.date(2026,9,6) + 15h (i.e. as the
// UTC calendar date + hour-of-day the KST instant falls on).
function toRulesTimestampExpr(kstIso) {
  const d = new Date(kstIso);
  const utcDate = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()));
  const hours = d.getUTCHours();
  return {
    dateExpr: `timestamp.date(${utcDate.getUTCFullYear()}, ${utcDate.getUTCMonth() + 1}, ${utcDate.getUTCDate()})`,
    hours,
    resolvedUtcIso: d.toISOString(),
  };
}

const { dateExpr, hours, resolvedUtcIso } = toRulesTimestampExpr(STAGING_PROGRAM_START_KST);

const semesterPattern = /function currentSemester\(\) \{[^}]*\}/;
const programStartPattern = /function programStart\(\) \{[^}]*\}/;

if (!semesterPattern.test(original)) throw new Error('currentSemester() pattern not found — firestore.rules must have changed shape');
if (!programStartPattern.test(original)) throw new Error('programStart() pattern not found — firestore.rules must have changed shape');

let staging = original
  .replace(
    semesterPattern,
    `function currentSemester() {\n      return '${STAGING_SEMESTER_ID}'; // STAGING override — see scripts/generate-staging-rules.mjs\n    }`,
  )
  .replace(
    programStartPattern,
    `// ${resolvedUtcIso} == ${STAGING_PROGRAM_START_KST} (Monday, staging week 1, KST) — STAGING override\n    function programStart() {\n      return ${dateExpr} + duration.value(${hours}, 'h');\n    }`,
  );

// Update the file-header comment so it doesn't claim to be the production calendar.
staging = staging.replace(
  /\/\/ Program calendar: PROGRAM_START and SEMESTER_ID below MUST match[\s\S]*?\/\/ -{10,}\n/,
  '// -----------------------------------------------------------------------\n',
);
staging = staging.replace(
  '// 15-week learning challenge — Firestore security rules.',
  `// 15-week learning challenge — Firestore security rules.\n//\n// *** STAGING VARIANT — generated by scripts/generate-staging-rules.mjs ***\n// Identical to firestore.rules in every way EXCEPT currentSemester() and\n// programStart(). Deployed ONLY to the staging Firebase project\n// (learning-challenge-staging), never to production. Do not hand-edit —\n// re-run the generator instead, so it can never silently drift from the\n// real, audited production rules.`,
);

// Verify: this is the actual guarantee the script exists to provide. A plain
// line-by-line diff is useless here — inserting header comment lines shifts
// every subsequent line number and makes a naive diff claim the entire file
// changed. Instead, normalize BOTH files by blanking out exactly the three
// regions this script is allowed to touch (the header comment block, and
// the bodies of currentSemester()/programStart(), each replaced by the same
// placeholder token in both copies) and then require the two normalized
// strings to be BYTE-IDENTICAL. If they're not, some other line drifted.
function normalize(rulesText) {
  return rulesText
    .replace(/\/\/ 15-week learning challenge[\s\S]*?\nservice cloud\.firestore \{/, '<<HEADER>>\nservice cloud.firestore {')
    .replace(/(?:\/\/[^\n]*\n\s*)?function currentSemester\(\) \{[^}]*\}/, '<<CURRENT_SEMESTER>>')
    .replace(/(?:\/\/[^\n]*\n\s*)*function programStart\(\) \{[^}]*\}/, '<<PROGRAM_START>>');
}

const normalizedOriginal = normalize(original);
const normalizedStaging = normalize(staging);
if (normalizedOriginal !== normalizedStaging) {
  console.error('Normalized original:\n', normalizedOriginal);
  console.error('Normalized staging:\n', normalizedStaging);
  throw new Error(
    'VERIFICATION FAILED: firestore.staging.rules differs from firestore.rules ' +
      'somewhere other than the header comment / currentSemester() / programStart(). ' +
      'Refusing to write the file — fix the generator before trusting its output.',
  );
}

writeFileSync(OUT, staging);
console.log(`Wrote ${OUT}`);
console.log('Verified: every rule outside currentSemester()/programStart() is byte-identical to firestore.rules.');
console.log(`  currentSemester() -> '${STAGING_SEMESTER_ID}'`);
console.log(`  programStart()    -> ${STAGING_PROGRAM_START_KST} (${resolvedUtcIso} UTC)`);
